    /// `--noop-health-probe`: request the unfiltered share set once, so the simulator's exception lists
    /// every type Apple refuses. Development aid only; it crashes by design when the list is incomplete.
    func probeShareSet() {
        var share = Set<HKSampleType>()
        for raw in Self.allQuantityIdentifiers {
            if let t = HKObjectType.quantityType(forIdentifier: .init(rawValue: raw)) { share.insert(t) }
        }
        for raw in Self.allCategoryIdentifiers {
            if let t = HKObjectType.categoryType(forIdentifier: .init(rawValue: raw)) { share.insert(t) }
        }
        share.insert(HKObjectType.audiogramSampleType())
        share.insert(HKSeriesType.heartbeat())
        share.insert(HKObjectType.electrocardiogramType())
        if #available(iOS 18.0, *) { share.insert(HKObjectType.stateOfMindType()) }
        let filtered = share.filter { !Self.shareDisallowed.contains($0.identifier) }
        print("[health-probe] requesting share for \(filtered.count) types")
        HKHealthStore().requestAuthorization(toShare: filtered, read: nil) { ok, error in
            print("[health-probe] finished ok=\(ok) error=\(String(describing: error))")
        }
    }
